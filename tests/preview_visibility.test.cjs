const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const visibility=vm.createContext({})
vm.runInContext(fs.readFileSync(__dirname+'/../ui/PreviewVisibility.js','utf8').replace(/^\.pragma library\s*/,''),visibility)
const output=(name='DP-1',patch={})=>({name,width:1920,height:1080,dpmsStatus:true,activeWorkspace:{id:1},solitaryBlockedBy:[],...patch})
const state=monitors=>({known:true,monitors,checkedAt:1000})
const allowed=(value,screen='DP-1',now=1250)=>visibility.allowed(value,screen,now)

assert.equal(allowed(state([output()])),true)
assert.equal(allowed(state([output(),output('DP-2')])),true)
assert.equal(allowed(state([output(),output('DP-2',{solitaryBlockedBy:['LOCK']})])),false,'A lock on any output suspends every capture')
assert.equal(allowed(state([output('DP-1',{solitaryBlockedBy:['WORKSPACE']}),output('DP-2',{solitaryBlockedBy:['WORKSPACE']})])),false)
for(const patch of [{disabled:true},{dpmsStatus:false},{width:0},{height:0},{solitaryBlockedBy:['WORKSPACE']},
  {solitaryBlockedBy:['LOCK']},{solitaryBlockedBy:null},{solitaryBlockedBy:'LOCK'}])
  assert.equal(allowed(state([output('DP-1',patch)])),false,JSON.stringify(patch))
assert.equal(allowed(state([output(),output('DP-2',{dpmsStatus:false})])),true,'Another powered-off output does not hide an awake card')
assert.equal(allowed(state([output('DP-1',{dpmsStatus:false}),output('DP-2')])),false)
assert.equal(allowed(state([output(),output()])),false,'Duplicate output identity is ambiguous')
assert.equal(allowed(state([output('DP-2')])),false)
assert.equal(allowed(state([output('DP-1',{solitaryBlockedBy:undefined})])),true,'Legacy output with a valid workspace remains supported')
for(const activeWorkspace of [undefined,null,{id:0},{id:-1},{}])
  assert.equal(allowed(state([output('DP-1',{solitaryBlockedBy:undefined,activeWorkspace})])),false)
for(const monitors of [[],null,{},[null],[output(),null]]) assert.equal(allowed(state(monitors)),false)
assert.equal(allowed({...state([output()]),known:false}),false)
assert.equal(allowed({...state([output()]),checkedAt:undefined}),false)
assert.equal(allowed(state([output()]),'DP-1',3000),true)
assert.equal(allowed(state([output()]),'DP-1',3001),false,'Stale state must not keep a live lease active')
assert.equal(allowed(state([output()]),'DP-1',999),false,'Clock discontinuity must fail closed')
assert.equal(allowed(null),false)
console.log('Preview visibility: session locks, target DPMS, unknown/stale states and legacy monitor fallback passed')
